CREATE DATABASE IF NOT EXISTS nomad_rp
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE nomad_rp;

CREATE TABLE IF NOT EXISTS accounts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  login VARCHAR(24) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS characters (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT UNSIGNED NOT NULL,
  first_name VARCHAR(24) NOT NULL,
  last_name VARCHAR(24) NOT NULL,
  gender ENUM('male','female') NOT NULL,
  cash BIGINT NOT NULL DEFAULT 500,
  bank BIGINT NOT NULL DEFAULT 2500,
  health DECIMAL(5,2) NOT NULL DEFAULT 100,
  hunger TINYINT UNSIGNED NOT NULL DEFAULT 100,
  thirst TINYINT UNSIGNED NOT NULL DEFAULT 100,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_characters_account FOREIGN KEY (account_id)
    REFERENCES accounts(id) ON DELETE CASCADE,
  INDEX idx_characters_account (account_id)
);
